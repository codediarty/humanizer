def T(head, rows):
    h = "".join("<th>%s</th>" % x for x in head)
    b = "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % c for c in r) for r in rows)
    return "<table><thead><tr>%s</tr></thead><tbody>%s</tbody></table>" % (h, b)


def UL(items):
    return "<ul>%s</ul>" % "".join("<li>%s</li>" % x for x in items)


